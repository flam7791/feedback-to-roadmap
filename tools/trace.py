"""Traceability gate: every backlog story marked Done must be proved by at least one test.

Reads docs/team/backlog.csv and scans tests/ for functions named test_<STORY>_... (US-04 -> test_US04_).
Fails (exit 1) when a Done story has no test, or a test names a story that is not in the backlog.
Prints a story -> tests matrix so a reviewer can see what "done" rests on.

    python tools/trace.py            # check
    python tools/trace.py --matrix   # also write docs/team/traceability.md
"""
from __future__ import annotations

import argparse
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEST_RE = re.compile(r"^def (test_(US\d{2})_\w+)\(", re.M)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--matrix", action="store_true", help="write docs/team/traceability.md")
    a = ap.parse_args()

    with open(ROOT / "docs" / "team" / "backlog.csv", newline="", encoding="utf-8") as f:
        stories = list(csv.DictReader(f))
    by_id = {s["id"]: s for s in stories}

    tests: dict[str, list[str]] = {}
    for p in sorted((ROOT / "tests").glob("test_*.py")):
        for name, sid in TEST_RE.findall(p.read_text(encoding="utf-8")):
            tests.setdefault(f"US-{sid[2:]}", []).append(f"{p.name}::{name}")

    errors = []
    for s in stories:
        if s["status"] == "Done" and not tests.get(s["id"]):
            errors.append(f"{s['id']} is Done but no test proves it")
    for sid in tests:
        if sid not in by_id:
            errors.append(f"tests reference {sid}, which is not in the backlog")

    done = [s for s in stories if s["status"] == "Done"]
    print(f"stories: {len(stories)}  done: {len(done)}  done with tests: "
          f"{sum(1 for s in done if tests.get(s['id']))}  test functions: {sum(len(v) for v in tests.values())}")

    if a.matrix:
        lines = ["# Traceability: backlog story -> tests", "",
                 "Generated by `python tools/trace.py --matrix`. CI fails if a Done story has no test.", "",
                 "| Story | Status | Title | Tests |", "|---|---|---|---|"]
        for s in stories:
            t = "<br>".join(f"`{x.split('::')[1]}`" for x in tests.get(s["id"], [])) or "-"
            lines.append(f"| {s['id']} | {s['status']} | {s['title']} | {t} |")
        (ROOT / "docs" / "team" / "traceability.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    for e in errors:
        print("FAIL:", e)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
